package flamingo.aprendendo.basico;

public class OperadoresParte02 {
    public static void main(String[] args) {
        /*
        * < menor que
        * > maior que
        * <= menor ou igual
        * >= maior ou igual
        * == igual a
        * != diferente de
        * */

        int numero01= 10;
        int numero02 = 15;
        System.out.println(numero01 < numero02);
        System.out.println(numero01 > numero02);
        System.out.println(numero02 <= numero01);
        System.out.println(numero01 >= numero02);
        System.out.println(numero01 == numero02);
        System.out.println(numero02 != numero01);

    }
}
